class PDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font("D", "", FONT_REGULAR)
        self.add_font("D", "B", FONT_BOLD)
        self.set_auto_page_break(True, 15)

    def footer(self):
        self.set_y(-12)
        self.set_font("D", "", 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 8, f"Финмодель и дизайн | стр. {self.page_no()}", align="C")

    def cover(self):
        self.add_page()
        self.set_font("D", "B", 20)
        self.set_text_color(25, 55, 95)
        self.multi_cell(0, 10, "Финансовая модель и дизайн-проект", align="C")
        self.ln(2)
        self.set_font("D", "B", 14)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 8, "Пивной супермаркет по модели видео «ПивМастер»", align="C")
        self.ln(6)
        self.set_font("D", "", 10)
        self.set_text_color(80, 80, 80)
        for line in [
            "Модель из видео vs рекомендуемая модель",
            "Примеры дизайн-проектов и планировок",
            f"Дата: {date.today().strftime('%d.%m.%Y')}",
            "Источник видео: youtu.be/vSRBrD8_K0o",
        ]:
            self.cell(0, 6, line, align="C")
            self.ln(6)

    def h1(self, t):
        self.ln(2)
        self.set_font("D", "B", 13)
        self.set_text_color(25, 55, 95)
        self.multi_cell(0, 8, t)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(2)

    def h2(self, t):
        self.ln(1)
        self.set_font("D", "B", 10.5)
        self.set_text_color(50, 50, 50)
        self.multi_cell(0, 6, t)
        self.ln(1)

    def p(self, t):
        self.set_font("D", "", 9.5)
        self.set_text_color(30, 30, 30)
        self.multi_cell(0, 5.2, t)
        self.ln(1)

    def b(self, t):
        self.set_font("D", "", 9.5)
        self.set_x(10)
        self.multi_cell(0, 5.2, f"• {t}")

    def box(self, t):
        self.set_fill_color(240, 246, 255)
        self.set_font("D", "B", 9.5)
        self.set_text_color(25, 55, 95)
        self.multi_cell(0, 5.5, t, border=1, fill=True)
        self.ln(2)

    def tbl(self, hdr, rows, w):
        self.set_font("D", "B", 8.5)
        self.set_fill_color(230, 236, 245)
        self.set_text_color(25, 55, 95)
        for c, ww in zip(hdr, w):
            self.cell(ww, 7, c, 1, 0, "L", True)
        self.ln()
        self.set_font("D", "", 8.5)
        self.set_text_color(30, 30, 30)
        self.set_fill_color(255, 255, 255)
        for row in rows:
            for c, ww in zip(row, w):
                self.cell(ww, 7, c, 1)
            self.ln()
        self.ln(2)

    def img(self, path, w=180, caption=""):
        if Path(path).exists():
            self.image(path, x=15, w=w)
            self.ln(2)
            if caption:
                self.set_font("D", "", 8)
                self.set_text_color(100, 100, 100)
                self.multi_cell(0, 4.5, caption)
                self.ln(2)


