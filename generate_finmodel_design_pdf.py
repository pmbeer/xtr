def make_floorplan(path: str, title: str, zones: list, color: str):
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.set_xlim(0, 16)
    ax.set_ylim(0, 10)
    ax.set_aspect("equal")
    ax.axis("off")
    ax.set_title(title, fontsize=11, fontweight="bold", pad=10)
    for z in zones:
        rect = patches.FancyBboxPatch(
            (z["x"], z["y"]), z["w"], z["h"],
            boxstyle="round,pad=0.05", linewidth=1.2,
            edgecolor="#2c4a7c", facecolor=z.get("color", color), alpha=0.75,
        )
        ax.add_patch(rect)
        ax.text(z["x"] + z["w"]/2, z["y"] + z["h"]/2, z["label"],
                ha="center", va="center", fontsize=8, wrap=True)
    plt.tight_layout()
    plt.savefig(path, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close()


